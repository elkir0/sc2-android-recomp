#!/usr/bin/env python3
"""closure-plus.py — passe 9q : complète une closure liftée EXISTANTE avec des racines manquantes, sans relift global.

Pour chaque racine (et, récursivement, chaque cible directe de dispatch absente de recomp_sc2_list.h et située dans
.text) : même lecteur PE, mêmes relocations, même étendue par descente bornée que scripts/lift-boot.py, lift par le
lift32_cpu donné. Sortie : un fichier C (les fonctions neuves, en-tête lift-boot) et la liste des VA ajoutées.

  closure-plus.py <lift-boot.py> <dossier tools/lift> <SC2.exe> <recomp_sc2_list.h> <sortie.c> <racine hex>…
"""
import importlib.util, re, sys
lb_path, lift_dir, exe, liste, sortie = sys.argv[1:6]
racines = [int(a, 16) for a in sys.argv[6:]]
spec = importlib.util.spec_from_file_location("liftboot", lb_path); lb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lb)
sys.path.insert(0, lift_dir)
import lift32_cpu as L
pe = lb.PE(exe)
L.IMAGE_BASE = pe.image_base
lifter = L.Lifter(None, pe.size_of_image, pe.read_va)
lifter.reloc_vas = pe.relocs()
text = next(s for s in pe.sections if s["name"] == ".text")
code_lo = pe.image_base + text["rva"]; code_hi = code_lo + text["vsize"]
connues = {int(m, 16) for m in re.findall(r"X\(([0-9A-F]{8})\)", open(liste).read())}

def etendue(va, plafond=0x4000):
    insns = {i.address: i for i in lifter.md.disasm(pe.read_va(va, plafond + 16), va)}
    pile, vus, fin = [va], set(), va
    while pile:
        a = pile.pop()
        while a in insns and a < va + plafond and a not in vus:
            vus.add(a); i = insns[a]; nxt = a + i.size; fin = max(fin, nxt); m = i.mnemonic.split()[-1]
            if m in ("ret", "retn", "retf", "iret", "iretd", "hlt", "int3", "ud2"): break
            if m.startswith("j") or m.startswith("loop"):
                op = i.operands[0] if i.operands else None
                if op is not None and op.type == L.X86_OP_IMM and va <= op.imm < va + plafond: pile.append(op.imm)
                if m == "jmp": break
            a = nxt
    return fin - va

file, faites, sources, echecs = list(racines), set(), {}, {}
while file:
    a = file.pop(0)
    if a in faites or a in connues: continue
    faites.add(a)
    n = etendue(a)
    try:
        src = lifter.lift_function(pe.read_va(a, n), a)
    except Exception as e:
        msg = f"{type(e).__name__}: {e}".replace('"', "'")[:120]; echecs[a] = msg
        src = (f"void L_{a:08X}(CPU *c)\n{{\n    /* lift32_cpu a échoué : {msg} */\n"
               f'    RECOMP_TODO(0x{a:08X}u, "fonction non liftable ({msg})");\n}}')
    sources[a] = src
    cibles = sorted({int(m.group(1), 16) for m in lb.DISPATCH_RE.finditer(src)})
    neuves = [t for t in cibles if code_lo <= t < code_hi and t not in connues and t not in faites]
    sys.stderr.write(f"[closure+] 0x{a:08X} : {n} o, {len(cibles)} cibles directes, {len(neuves)} absentes de la closure"
                     f"{' : ' + ' '.join('%08X' % t for t in neuves) if neuves else ''}{'  ÉCHEC ' + echecs[a] if a in echecs else ''}\n")
    file += neuves
with open(sortie, "w") as f:
    f.write("/* AUTO-GENERATED by lift32_cpu.py (pcrecomp) via recomp-sc2/tools/lift/closure-plus.py - do not edit */\n"
            '#include "cpu.h"\n#include "sc2_lifted.h"\n\n')
    for a in sorted(sources): f.write(sources[a] + "\n\n")
print(" ".join("%08X" % a for a in sorted(sources)))
sys.stderr.write(f"[closure+] {len(sources)} fonction(s) neuve(s), {len(echecs)} échec(s) de lift\n")

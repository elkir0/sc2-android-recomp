#!/usr/bin/env bash
# theora-android.sh — libogg 1.3.5 + libtheora 1.1.1 (decoder only, BSD-style licences) cross-compiled for
# Android aarch64 with the NDK, as STATIC libraries (no assembly, -O2 -fPIC, ready to link into a .so).
#
# FR : télécharge les sources OFFICIELLES Xiph.Org (sha256 vérifiés), compile le décodeur Theora et libogg
#      pour aarch64-linux-android<API>, et produit des archives statiques déterministes :
# EN : downloads the OFFICIAL Xiph.Org sources (sha256-checked), builds the Theora decoder and libogg for
#      aarch64-linux-android<API>, and produces deterministic static archives:
#
#   $OUT/lib/libogg.a  $OUT/lib/libtheoradec.a
#   $OUT/include/ogg/{ogg.h,os_types.h,config_types.h}  $OUT/include/theora/{codec.h,theoradec.h}
#   $OUT/EMPREINTES.txt   (sha256 of every produced file / sha256 de chaque fichier produit)
#
# Variables :
#   ANDROID_NDK_HOME (or ANDROID_NDK)  NDK root (required / requis) — tested with r28c (28.2.13676358)
#   ANDROID_API      minimum API level of the target triple (default 26)
#   THEORA_SRC       where sources are downloaded/unpacked (default ${XDG_CACHE_HOME:-~/.cache}/theora-android)
#   OUT              output prefix (default $THEORA_SRC/android-arm64)
#
# Usage :
#   ANDROID_NDK_HOME=/path/to/android-ndk-r28c ./scripts/theora-android.sh
#   then, in CMake / puis dans CMake :
#     target_include_directories(app PRIVATE $OUT/include)
#     target_link_libraries(app PRIVATE $OUT/lib/libtheoradec.a $OUT/lib/libogg.a)   # this order / cet ordre
#
# Idempotent: rebuilds everything on each call (~15 C files, seconds). Two runs give identical sha256
# (llvm-ar deterministic mode, -ffile-prefix-map). / Deux exécutions donnent des sha256 identiques.
set -euo pipefail
NDK="${ANDROID_NDK_HOME:-${ANDROID_NDK:-}}"
API="${ANDROID_API:-26}"
SRC="${THEORA_SRC:-${XDG_CACHE_HOME:-$HOME/.cache}/theora-android}"
OUT="${OUT:-$SRC/android-arm64}"
[ -n "$NDK" ] && [ -f "$NDK/source.properties" ] || { echo "ANDROID_NDK_HOME must point to an Android NDK root" >&2; exit 1; }
echo "NDK $(sed -n 's/^Pkg.Revision = //p' "$NDK/source.properties") (tested: 28.2.13676358), API $API"

# --- 1. official sources, sha256-checked / sources officielles, sha256 vérifiés --------------------------
mkdir -p "$SRC/dl"
prendre() {   # <url> <sha256>
  local f="$SRC/dl/$(basename "$1")"
  [ -f "$f" ] || curl -fL -o "$f" "$1"
  echo "$2  $f" | sha256sum -c - >/dev/null || { echo "unexpected sha256: $f" >&2; exit 1; }
  tar xf "$f" -C "$SRC"
}
prendre https://downloads.xiph.org/releases/ogg/libogg-1.3.5.tar.xz \
        c4d91be36fc8e54deae7575241e03f4211eb102afb3fc0775fbbc1b740016705
prendre https://downloads.xiph.org/releases/theora/libtheora-1.1.1.tar.xz \
        f36da409947aa2b3dcc6af0a8c2e3144bc19db2ed547d64e9171c59c66561c61
OGG="$SRC/libogg-1.3.5"; TH="$SRC/libtheora-1.1.1"

# --- 2. cross-compile / compilation croisée ----------------------------------------------------------------
LLVM="$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin"
CC="$LLVM/aarch64-linux-android$API-clang"; AR="$LLVM/llvm-ar"
[ -x "$CC" ] || { echo "compiler not found: $CC" >&2; exit 1; }
rm -rf "${OUT:?}"; mkdir -p "$OUT/lib" "$OUT/include/ogg" "$OUT/include/theora" "$OUT/obj/ogg" "$OUT/obj/theora"
# libogg's config_types.h is normally generated by configure: fixed-width types are enough on aarch64.
cat > "$OUT/include/ogg/config_types.h" <<'EOF'
#ifndef __CONFIG_TYPES_H__
#define __CONFIG_TYPES_H__
#include <stdint.h>
typedef int16_t ogg_int16_t;
typedef uint16_t ogg_uint16_t;
typedef int32_t ogg_int32_t;
typedef uint32_t ogg_uint32_t;
typedef int64_t ogg_int64_t;
typedef uint64_t ogg_uint64_t;
#endif
EOF
cp "$OGG"/include/ogg/ogg.h "$OGG"/include/ogg/os_types.h "$OUT/include/ogg/"
cp "$TH"/include/theora/codec.h "$TH"/include/theora/theoradec.h "$OUT/include/theora/"
FL=(-O2 -fPIC -w -ffile-prefix-map="$SRC"=theora -I"$OUT/include")
for f in bitwise framing; do "$CC" "${FL[@]}" -c "$OGG/src/$f.c" -o "$OUT/obj/ogg/$f.o"; done
# decoder only, generic C (no x86 asm) / décodeur seul, C générique (pas d'asm x86)
for f in bitpack decinfo decode dequant fragment huffdec idct info internal quant state; do
  "$CC" "${FL[@]}" -I"$TH/include" -c "$TH/lib/$f.c" -o "$OUT/obj/theora/$f.o"
done
"$AR" rcsD "$OUT/lib/libogg.a" "$OUT"/obj/ogg/*.o
"$AR" rcsD "$OUT/lib/libtheoradec.a" "$OUT"/obj/theora/*.o
rm -rf "${OUT:?}/obj"

# --- 3. report / bilan --------------------------------------------------------------------------------------
{ echo "libogg 1.3.5 + libtheora 1.1.1 (decoder), aarch64-linux-android$API, NDK $(sed -n 's/^Pkg.Revision = //p' "$NDK/source.properties")"
  ( cd "$OUT" && sha256sum lib/*.a include/*/*.h ); } > "$OUT/EMPREINTES.txt"
for a in "$OUT"/lib/*.a; do
  printf '%s : %s bytes, %s objects, machine %s\n' "$(basename "$a")" "$(stat -c %s "$a")" "$("$AR" t "$a" | wc -l)" \
    "$("$LLVM/llvm-readelf" -h "$a" | awk '/Machine:/{print $2; exit}')"
done
sed 1d "$OUT/EMPREINTES.txt" | grep '\.a$'
